// Generates src/styles/tokens.css and src/tokens.ts from tokens/tokens.json.
// Run: npm run tokens
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const src = JSON.parse(readFileSync(resolve(root, 'tokens/tokens.json'), 'utf8'));

const get = (path) => path.split('.').reduce((o, k) => (o == null ? undefined : o[k]), src);
const resolveRef = (v, seen = new Set()) => {
  if (typeof v !== 'string') return v;
  return v.replace(/\{([^}]+)\}/g, (_, p) => {
    if (seen.has(p)) throw new Error(`Circular token reference: ${p}`);
    const hit = get(p);
    if (hit === undefined) throw new Error(`Unknown token reference: {${p}}`);
    return resolveRef(hit, new Set([...seen, p]));
  });
};
const flat = (obj, prefix = []) =>
  Object.entries(obj).flatMap(([k, v]) =>
    k.startsWith('$') ? [] : v && typeof v === 'object' ? flat(v, [...prefix, k]) : [[[...prefix, k].join('-'), resolveRef(v)]]);
const decls = (pairs, prefix, indent = '  ') => pairs.map(([k, v]) => `${indent}--mz-${prefix ? prefix + '-' : ''}${k}: ${v};`).join('\n');

const staticGroups = ['color', 'font', 'type', 'space', 'radius', 'size', 'shadow', 'blur', 'motion'];
// Values that are not valid CSS custom-property values (URLs with ';') stay JS-only.
const cssSafe = ([, v]) => !String(v).includes(';');
const staticDecls = staticGroups.map((g) => `  /* ${g} */\n` + decls(flat(src[g]).filter(cssSafe), g)).join('\n');
const themeDecls = (name) => decls(flat(src.theme[name]), '');
const moodDecls = (mood, theme) => decls(flat(src.mood[mood][theme] || {}), '');

const css = `/* AUTO-GENERATED by scripts/build-tokens.mjs from tokens/tokens.json — do not edit by hand. */

:root {
${staticDecls}
}

/* Theme: Abyss (default, dark) */
:root,
[data-theme="abyss"] {
  color-scheme: dark;
${themeDecls('abyss')}
}

/* Theme: Pearl (light — brunch, print, receipts) */
[data-theme="pearl"] {
  color-scheme: light;
${themeDecls('pearl')}
}

/* Mood: Lantern — amber leads (dining, brunch). Glow is the default mood. */
[data-mood="lantern"],
[data-theme="abyss"][data-mood="lantern"],
[data-theme="abyss"] [data-mood="lantern"] {
${moodDecls('lantern', 'abyss')}
}
[data-theme="pearl"][data-mood="lantern"],
[data-theme="pearl"] [data-mood="lantern"] {
${moodDecls('lantern', 'pearl')}
}
`;

const resolvedTree = (obj) =>
  Object.fromEntries(Object.entries(obj).filter(([k]) => !k.startsWith('$'))
    .map(([k, v]) => [k, v && typeof v === 'object' ? resolvedTree(v) : resolveRef(v)]));

const ts = `/* AUTO-GENERATED by scripts/build-tokens.mjs from tokens/tokens.json — do not edit by hand. */
/** Raw token values (resolved). Prefer CSS variables (var(--mz-*)) in styles; use these for JS (charts, canvas, native apps). */
export const tokens = ${JSON.stringify(resolvedTree(src), null, 2)} as const;

export type Tokens = typeof tokens;
export type ThemeName = keyof typeof tokens.theme;
export type Mood = 'glow' | 'lantern';

/** CSS variable reference helper: cssVar('accent') -> 'var(--mz-accent)' */
export const cssVar = (name: string) => \`var(--mz-\${name})\`;
`;

mkdirSync(resolve(root, 'src/styles'), { recursive: true });
writeFileSync(resolve(root, 'src/styles/tokens.css'), css);
writeFileSync(resolve(root, 'src/tokens.ts'), ts);
console.log('tokens: wrote src/styles/tokens.css and src/tokens.ts');
