#!/usr/bin/env node
// ONE-OFF: turns the brunch and dinner items in design/screens/parked-list-menu.dc.html into
// lib/menu/items.ts. After that file has been reviewed it is the source of truth and is edited by
// hand; this script refuses to overwrite it unless you pass --force.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import vm from "node:vm";

const root = new URL("..", import.meta.url).pathname;
const out = `${root}lib/menu/items.ts`;
if (existsSync(out) && !process.argv.includes("--force")) {
  console.error("lib/menu/items.ts already exists and may have been edited by hand. Use --force to overwrite.");
  process.exit(1);
}

const html = readFileSync(`${root}design/screens/parked-list-menu.dc.html`, "utf8");
const start = html.indexOf("const DATA = {");
const end = html.indexOf("\n    };", start);
if (start < 0 || end < 0) throw new Error("could not find DATA in the parked list");
const literal = html.slice(start + "const DATA = ".length, end + "\n    }".length);

// The screen file prices in thousands and calls helpers i() (item) and sec() (section).
const i = (n, v, p, x) => ({ name: n, ru: v, price: p ? p * 1000 : undefined, ...(x ?? {}) });
const sec = (id, title, ru, _banner, _alt, _note, items) => ({ id, title: { en: title, ru }, items });
const data = vm.runInNewContext(`(${literal})`, { i, sec });

const FOOD_VAT = "8%";
let count = 0;
const menus = {};
// The screen file also holds condensed "drinks" and "hookah" mock data; only the two food menus
// come from real PDFs, so only those are taken.
for (const [menu, sections] of Object.entries(data).filter(([k]) => k === "brunch" || k === "dinner")) {
  menus[menu] = sections.map((s) => ({
    id: s.id,
    title: s.title,
    items: s.items.map((it) => {
      count++;
      const unconfirmed = [];
      if (menu === "brunch") unconfirmed.push("name"); // English brunch names are translations of the Russian-only PDF
      if (it.veg) unconfirmed.push("veg");
      if (it.spicy) unconfirmed.push("spicy");
      return {
        name: it.name,
        ru: it.ru,
        ...(it.price ? { price: it.price } : {}),
        ...(it.veg ? { veg: true } : {}),
        ...(it.spicy ? { spicy: true } : {}),
        ...(unconfirmed.length ? { unconfirmed } : {})
      };
    })
  }));
}

const body = JSON.stringify(menus, null, 2).replace(/"([a-z]+)":/g, "$1:");
writeFileSync(
  out,
  `// Source of truth for the text menu (hidden layer for search engines and screen readers).
// First generated by scripts/extract-parked-menu.mjs from the parked list screen, then reviewed by hand.
// Prices are full VND (the printed menus show thousands). Food prices include ${FOOD_VAT} VAT.
// "unconfirmed" lists what the owner has not confirmed yet: name (English brunch names are
// translations of the Russian-only PDF), veg and spicy markers. \`npm run menu:unconfirmed\` lists them.

export type Unconfirmed = "name" | "veg" | "spicy";

export type MenuItem = {
  name: string;
  ru: string;
  price?: number;
  veg?: boolean;
  spicy?: boolean;
  unconfirmed?: Unconfirmed[];
};

export type MenuSection = { id: string; title: { en: string; ru: string }; items: MenuItem[] };

export const FOOD_MENUS: Record<"brunch" | "dinner", MenuSection[]> = ${body};
`
);
console.log(`wrote lib/menu/items.ts: ${count} items in ${Object.values(menus).flat().length} sections`);
